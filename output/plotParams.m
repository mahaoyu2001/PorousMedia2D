function [curLineWidth, axLineWidth, markerSize, ...
    axTickFontSize, axLabelFontSize, lgdFontSize, ...
    axTickFontName, axLabelFontName, lgdFontName, colorList] = plotParams(varargin)
%PLOTPARAMS Return consistent publication-figure style parameters.
%   Name-value inputs override the defaults. COLORGROUP may be ``default``,
%   ``matlab`` or ``multi``.

defaults = struct(...
    'curLineWidth', 1.5, ...
    'axLineWidth', 0.75, ...
    'markerSize', 1, ...
    'axTickFontSize', 9.5, ...
    'axLabelFontSize', 11, ...
    'lgdFontSize', 11, ...
    'axTickFontName', 'Times New Roman', ...
    'axLabelFontName', 'Times New Roman', ...
    'lgdFontName', 'Times New Roman', ...
    'colorGroup', 'default');

colorSchemes = containers.Map(...
    {'default', 'matlab', 'multi'}, ...
    {...
        {[0.7804 0.1333 0.1569]; ...
         [0.0471 0.3059 0.6078]; ...
         [0.9765 0.5608 0.2039]}, ...
        {[0 0.4470 0.7410]; ...
         [0.8500 0.3250 0.0980]; ...
         [0.9290 0.6940 0.1250]; ...
         [0.4940 0.1840 0.5560]; ...
         [0.4660 0.6740 0.1880]; ...
         [0.3010 0.7450 0.9330]; ...
         [0.6350 0.0780 0.1840]}, ...
        {[0.7804 0.1333 0.1569]; ...
         [0.0471 0.3059 0.6078]; ...
         [0.1176 0.5647 0.2627]; ...
         [0.8902 0.4471 0.1333]; ...
         [0.5804 0.1569 0.5569]; ...
         [0.1725 0.6275 0.7922]; ...
         [0.8392 0.6784 0.1529]; ...
         [0.5490 0.3373 0.2941]; ...
         [0.0902 0.7451 0.8118]; ...
         [0.4980 0.4980 0.4980]}});

positiveScalar = @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0;
p = inputParser;
addParameter(p, 'curLineWidth', defaults.curLineWidth, positiveScalar);
addParameter(p, 'axLineWidth', defaults.axLineWidth, positiveScalar);
addParameter(p, 'markerSize', defaults.markerSize, positiveScalar);
addParameter(p, 'axTickFontSize', defaults.axTickFontSize, positiveScalar);
addParameter(p, 'axLabelFontSize', defaults.axLabelFontSize, positiveScalar);
addParameter(p, 'lgdFontSize', defaults.lgdFontSize, positiveScalar);
addParameter(p, 'axTickFontName', defaults.axTickFontName, @ischar);
addParameter(p, 'axLabelFontName', defaults.axLabelFontName, @ischar);
addParameter(p, 'lgdFontName', defaults.lgdFontName, @ischar);
addParameter(p, 'colorGroup', defaults.colorGroup, ...
    @(x) ischar(x) && isKey(colorSchemes, x));
parse(p, varargin{:});

curLineWidth = p.Results.curLineWidth;
axLineWidth = p.Results.axLineWidth;
markerSize = p.Results.markerSize;
axTickFontSize = p.Results.axTickFontSize;
axLabelFontSize = p.Results.axLabelFontSize;
lgdFontSize = p.Results.lgdFontSize;
axTickFontName = p.Results.axTickFontName;
axLabelFontName = p.Results.axLabelFontName;
lgdFontName = p.Results.lgdFontName;
colorList = colorSchemes(p.Results.colorGroup);
end
